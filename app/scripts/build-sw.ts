// Build step: write app/sw.js, the service worker that makes "runs offline" true after one visit.
// It precaches every file the app needs; the cache name carries a hash of their contents, so a new
// build replaces the old cache instead of serving stale code. Usage: node app/scripts/build-sw.ts
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const app = fileURLToPath(new URL("..", import.meta.url));
const walk = (d: string): string[] =>
  readdirSync(join(app, d)).flatMap((f) => (statSync(join(app, d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));

const files = [
  "index.html", "styles.css", "anchor.wasm", "demo-events.json", "manifest.webmanifest",
  ...walk("icons"), ...walk("fonts").filter((f) => f.endsWith(".woff2")), ...walk("dist").filter((f) => f.endsWith(".js")),
].map((f) => relative(app, join(app, f)).replace(/\\/g, "/")).sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(app, f)));
const version = hash.digest("hex").slice(0, 12);

writeFileSync(join(app, "sw.js"), `// Generated by app/scripts/build-sw.ts; do not edit.
// Cache-first for the app's own files, so ANCHOR opens and runs with no network (N1).
const CACHE = "anchor-${version}";
const FILES = ${JSON.stringify(["./", ...files], null, 0)};
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(caches.keys()
  .then((ks) => Promise.all(ks.filter((k) => k.startsWith("anchor-") && k !== CACHE).map((k) => caches.delete(k))))
  .then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit ?? fetch(e.request)));
});
`);
console.log(`sw.js: ${files.length} files, cache anchor-${version}`);
