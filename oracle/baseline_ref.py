"""Independent reference for core/src/baseline.rs (ADR-0004).

Differences from the Rust implementation, on purpose:
- posterior states are computed with the *batch* conjugate formulas over the accepted prefix,
  not the sequential update;
- the predictive z uses scipy.stats (t.sf / norm.isf), not the hand-written special functions.

Writes oracle/vectors/baseline_vectors.txt. Run: py -I oracle/baseline_ref.py
"""
import math
import os

import numpy as np
from scipy import stats

ROLLING_CAP, WINDOW, WINSOR_SD, Z_CAP = 7.0, 14, 4.0, 8.0


def batch(prior, xs):
    m0, k0, a0, b0 = prior
    n = len(xs)
    if n == 0:
        return prior
    xbar = sum(xs) / n
    ss = sum((x - xbar) ** 2 for x in xs)
    kn = k0 + n
    return ((k0 * m0 + n * xbar) / kn, kn, a0 + n / 2, b0 + ss / 2 + k0 * n * (xbar - m0) ** 2 / (2 * kn))


def predictive(s):
    m, k, a, b = s
    return m, math.sqrt(b * (k + 1) / (a * k)), 2 * a


def z_of(s, y):
    loc, scale, df = predictive(s)
    t = (y - loc) / scale
    z = stats.norm.isf(stats.t.sf(t, df)) if t > 0 else stats.norm.ppf(stats.t.cdf(t, df))
    return float(np.clip(z, -Z_CAP, Z_CAP))


def anchor(pop, pre):
    mu, tau2, sigma2, nu_p = pop
    n0 = len(pre)
    pseudo = sigma2 / tau2
    mean = sum(pre) / n0 if n0 else mu
    ss = sum((v - mean) ** 2 for v in pre)
    kappa = n0 + pseudo
    b = pseudo / kappa
    return (b * mu + (1 - b) * mean, kappa, (nu_p + max(n0 - 1, 0)) / 2, (nu_p * sigma2 + ss) / 2)


def rolling(pop, anc, window):
    nu_p = pop[3]
    c = min(anc[1], ROLLING_CAP)
    a = min(anc[2], (nu_p + c - 1) / 2)
    prior = (anc[0], c, a, a * anc[3] / anc[2])
    accepted = []
    for y in window[-WINDOW:] if window else []:
        loc, scale, _ = predictive(batch(prior, accepted))
        accepted.append(min(max(y, loc - WINSOR_SD * scale), loc + WINSOR_SD * scale))
    return batch(prior, accepted)


if __name__ == "__main__":
    rng = np.random.default_rng(7)
    out = ["# generated by oracle/baseline_ref.py - pop | preflight | window | y | m0,k0,a0,b0,m,k,a,b,z"]
    r = lambda v: repr(float(v))
    for i in range(300):
        pop = (rng.uniform(-1, 1), math.exp(rng.uniform(math.log(0.05), math.log(2))),
               math.exp(rng.uniform(math.log(0.1), math.log(3))), float(rng.choice([2, 3, 5, 10])))
        mu_i = pop[0] + math.sqrt(pop[1]) * rng.normal()
        sd = math.sqrt(pop[2])
        pre = list(mu_i + sd * rng.normal(size=int(rng.choice([0, 1, 2, 3, 5, 10, 30, 100]))))
        win = list(mu_i + 0.3 + sd * rng.normal(size=int(rng.integers(0, 21))))
        if win and i % 4 == 0:
            win[int(rng.integers(0, len(win)))] += 20 * sd
        y = mu_i + sd * float(rng.choice([0.0, 1.0, -2.5, 6.0, -40.0, 1e3]))
        anc = anchor(pop, pre)
        roll = rolling(pop, anc, win)
        vals = list(anc) + list(roll) + [z_of(roll, y)]
        out.append("\t".join([",".join(map(r, pop)), ",".join(map(r, pre)), ",".join(map(r, win)), r(y),
                              ",".join(map(r, vals))]))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "baseline_vectors.txt")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"vectors: {len(out) - 1}")
