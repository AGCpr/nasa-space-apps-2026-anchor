"""Reference xoshiro256** / SplitMix64 / Box-Muller / Lemire bounded draws for core/src/rng.rs.

Writes oracle/vectors/rng_vectors.txt. Run: py -I oracle/rng_ref.py
"""
import math
import os

M = (1 << 64) - 1


def rotl(x, k):
    return ((x << k) | (x >> (64 - k))) & M


class Rng:
    def __init__(self, seed):
        s = seed & M
        out = []
        for _ in range(4):
            s = (s + 0x9E3779B97F4A7C15) & M
            z = s
            z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M
            z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M
            out.append(z ^ (z >> 31))
        self.s = out

    def next_u64(self):
        s = self.s
        result = (rotl((s[1] * 5) & M, 7) * 9) & M
        t = (s[1] << 17) & M
        s[2] ^= s[0]
        s[3] ^= s[1]
        s[1] ^= s[2]
        s[0] ^= s[3]
        s[2] ^= t
        s[3] = rotl(s[3], 45)
        return result

    def uniform(self):
        return (self.next_u64() >> 11) * (1.0 / (1 << 53))

    def normal(self):
        u1 = 1.0 - self.uniform()
        u2 = self.uniform()
        return math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)

    def below(self, n):
        threshold = ((-n) & M) % n
        while True:
            m = self.next_u64() * n
            if (m & M) >= threshold:
                return m >> 64


if __name__ == "__main__":
    out = ["# generated by oracle/rng_ref.py"]
    for seed in (0, 1, 42, 2 ** 64 - 1):
        r = Rng(seed)
        out.append(f"u64\t{seed}\t" + ",".join(str(r.next_u64()) for _ in range(200)))
    for seed in (3, 2026):
        r = Rng(seed)
        out.append(f"normal\t{seed}\t" + ",".join(repr(r.normal()) for _ in range(200)))
    for seed, n in ((5, 7), (6, 1000), (7, 2 ** 63 + 5)):
        r = Rng(seed)
        out.append(f"below\t{seed}\t{n}\t" + ",".join(str(r.below(n)) for _ in range(200)))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "rng_vectors.txt")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"streams: {len(out) - 1}")
