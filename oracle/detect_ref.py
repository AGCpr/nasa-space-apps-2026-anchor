"""Reference for the deterministic parts of core/src/detect.rs (ADR-0005): CUSUM paths,
same-day combination and the drift test (scipy for the t -> normal mapping).

Writes oracle/vectors/detect_vectors.txt. Run: py -I oracle/detect_ref.py
"""
import math
import os

import numpy as np
from scipy import stats

K_REF, DRIFT_WINDOW, DRIFT_MIN, ALPHA = 0.5, 28, 14, 0.01
STEP_CAP = 3.0  # cap on one day's increment (core/src/detect.rs)
r = lambda v: repr(float(v))


def cusum_path(zs, sign, h):
    s, out = 0.0, []
    for z in zs:
        s = max(0.0, s + min(sign * z, STEP_CAP) - K_REF)  # capped increment (detect.rs STEP_CAP)
        if s > h:
            s = 0.0
            out.append(-1.0)
        else:
            out.append(s)
    return out


def day_value(zs, rho):
    m = len(zs)
    return (sum(zs) / m) / math.sqrt((1 + (m - 1) * rho) / m)


def drift(values, sign):
    v = np.asarray(values[-DRIFT_WINDOW:], float)
    n = len(v)
    if n < DRIFT_MIN:
        return [-1.0, float(n)]
    x = np.arange(n, dtype=float)
    slope = np.sum((x - x.mean()) * (v - v.mean())) / np.sum((x - x.mean()) ** 2)
    resid = v - v.mean() - slope * (x - x.mean())
    ssr = float(np.sum(resid ** 2))
    phi = min(max(float(np.sum(resid[1:] * resid[:-1]) / ssr), 0.0), 0.9) if ssr > 0 else 0.0
    se = math.sqrt(ssr / (n - 2) / np.sum((x - x.mean()) ** 2) * (1 + phi) / (1 - phi))
    t = sign * slope / se if se > 0 else (math.inf if sign * slope > 0 else -math.inf if sign * slope < 0 else 0.0)
    if math.isinf(t):
        z = t
    elif t > 0:
        z = stats.norm.isf(stats.t.sf(t, n - 2))
    else:
        z = stats.norm.ppf(stats.t.cdf(t, n - 2))
    sen = float(np.median([(v[j] - v[i]) / (j - i) for i in range(n) for j in range(i + 1, n)]))
    return [slope, sen, phi, z, 1.0 if z > stats.norm.ppf(1 - ALPHA) else 0.0]


if __name__ == "__main__":
    rng = np.random.default_rng(13)
    out = ["# generated by oracle/detect_ref.py"]
    for i in range(60):
        sign, name = (1, "up") if i % 2 == 0 else (-1, "down")
        n = int(rng.choice([5, 13, 14, 20, 28, 40]))
        phi = rng.uniform(0, 0.7)
        e = rng.normal(size=n)
        y = np.empty(n)
        y[0] = e[0]
        for t in range(1, n):
            y[t] = phi * y[t - 1] + math.sqrt(1 - phi ** 2) * e[t]
        y += sign * rng.choice([0.0, 0.02, 0.06, 0.15]) * np.arange(n)
        if i == 7:
            y = np.full(n, 0.3)  # constant series: zero residuals
        out.append(f"drift\t{name}\t{','.join(map(r, y))}\t{','.join(map(r, drift(list(y), sign)))}")
    for i in range(30):
        sign, name = (1, "up") if i % 2 == 0 else (-1, "down")
        zs = rng.normal(size=60) + sign * rng.choice([0.0, 1.0, 2.0])
        h = float(rng.choice([2.0, 3.67, 5.0]))
        out.append(f"cusum\t{name}\t{r(h)}\t{','.join(map(r, zs))}\t{','.join(map(r, cusum_path(zs, sign, h)))}")
    for i in range(20):
        zs = list(rng.normal(size=int(rng.integers(1, 4))))
        rho = float(rng.choice([0.0, 0.3, 0.5, 0.9]))
        out.append(f"dayvalue\tup\t{r(rho)}\t{','.join(map(r, zs))}\t{r(day_value(zs, rho))}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "detect_vectors.txt")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"vectors: {len(out) - 1}")
