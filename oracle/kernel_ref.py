"""Reference safety kernel (third implementation of ADR-0003), plus exhaustive vector generator.

Writes oracle/vectors/kernel_vectors.txt, consumed by kernel A (Rust) and kernel B (TypeScript).
Run: py -I oracle/kernel_ref.py
"""
import hashlib
import os
import random
import re

I64_MIN, I64_MAX = -(2 ** 63), 2 ** 63 - 1
KEY = re.compile(r"^[a-z0-9_]{1,32}$")
INT = re.compile(r"^(0|-?[1-9][0-9]*)$")


def parse_table(s):
    """Return list of (id, indicator, op, limit, share) or raise ValueError."""
    if not s.startswith("t1|"):
        raise ValueError("header")
    body = s[3:]
    lines = []
    if body == "":
        return lines
    for item in body.split(";"):
        f = item.split(",")
        if len(f) != 6:
            raise ValueError("fields")
        if not INT.match(f[0]) or not INT.match(f[3]):
            raise ValueError("int")
        lid, limit = int(f[0]), int(f[3])
        if not (0 <= lid <= 65535) or not (I64_MIN <= limit <= I64_MAX):
            raise ValueError("range")
        if lines and lines[-1][0] >= lid:
            raise ValueError("order")
        if not KEY.match(f[1]) or f[2] not in ("above", "below"):
            raise ValueError("key/op")
        share = {("phys", "1"): True, ("high", "0"): False, ("high", "1"): True}.get((f[4], f[5]))
        if share is None:
            raise ValueError("class")
        lines.append((lid, f[1], f[2], limit, share))
        if len(lines) > 64:
            raise ValueError("too many")
    return lines


def evaluate(lines, indicator, value):
    out = []
    for lid, ind, op, limit, share in lines:
        if ind == indicator and ((op == "above" and value > limit) or (op == "below" and value < limit)):
            out.append((lid, share))
    return out


def critical_points(limits):
    pts = {I64_MIN, I64_MAX, 0}
    for l in limits:
        pts.update(v for v in (l - 1, l, l + 1) if I64_MIN <= v <= I64_MAX)
    pts = sorted(pts)
    mids = [(a + b) // 2 for a, b in zip(pts, pts[1:]) if b - a > 1]
    return sorted(set(pts) | set(mids))


def fmt(hits):
    return ",".join(f"{i}:{int(s)}" for i, s in hits) or "none"


def random_table(rng):
    inds = [f"ind_{k}" for k in range(rng.randint(1, 6))]
    n = rng.randint(1, 64)
    ids = sorted(rng.sample(range(0, 65536), n))
    parts = []
    for i in ids:
        limit = rng.choice([rng.randint(-2000, 2000), rng.randint(I64_MIN, I64_MAX), I64_MIN, I64_MAX, 0])
        cls, consent = rng.choice([("phys", "1"), ("high", "0"), ("high", "1")])
        parts.append(f"{i},{rng.choice(inds)},{rng.choice(['above', 'below'])},{limit},{cls},{consent}")
    return "t1|" + ";".join(parts)


TABLES = [
    "t1|1,spo2,below,900,phys,1;2,spo2,below,850,phys,1;3,hr_rest,above,1300,phys,1;4,hr_rest,below,350,phys,1;"
    "5,sbp,above,1800,phys,1;6,temp_c,above,390,phys,1;7,temp_c,below,350,phys,1;8,cssrs_plan,above,0,high,0;"
    "9,cssrs_intent,above,0,high,1",
    f"t1|1,x,above,{I64_MAX},phys,1;2,x,below,{I64_MIN},phys,1;3,x,above,{I64_MIN},high,1;4,x,below,{I64_MAX},high,0",
    "t1|",
]

REJECTS = [
    "1,spo2,below,900,phys,1",
    "t1|1,spo2,below,900,phys,1;1,hr,above,1,phys,1",
    "t1|2,spo2,below,900,phys,1;1,hr,above,1,phys,1",
    "t1|1,spo2,under,900,phys,1",
    "t1|1,spo2,below,900,phys,0",
    "t1|01,spo2,below,900,phys,1",
    "t1|1,spo2,below,-0,phys,1",
    "t1|1,SpO2,below,900,phys,1",
    "t1|1,spo2,below,900,phys",
    "t1|65536,spo2,below,900,phys,1",
    "t1|1,spo2,below,9223372036854775808,phys,1",
    "t1|1,spo2,below,900,high,2",
    "t1|" + ";".join(f"{i},a,above,0,phys,1" for i in range(65)),
]

if __name__ == "__main__":
    rng = random.Random(20261110)
    tables = TABLES + [random_table(rng) for _ in range(25)]
    out = ["# generated by oracle/kernel_ref.py - do not edit"]
    cases = 0
    for t in tables:
        lines = parse_table(t)
        out.append(f"table\t{t}")
        out.append(f"digest\t{hashlib.sha256(t.encode('ascii')).hexdigest()}")
        for ind in sorted({l[1] for l in lines}) + ["unknown_ind"]:
            for v in critical_points([l[3] for l in lines if l[1] == ind]):
                out.append(f"case\t{ind}\t{v}\t{fmt(evaluate(lines, ind, v))}")
                cases += 1
    for r in REJECTS:
        try:
            parse_table(r)
            raise SystemExit(f"reference accepted an invalid table: {r}")
        except ValueError:
            out.append(f"reject\t{r}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "kernel_vectors.txt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    # self-checks on the reference itself
    assert evaluate(parse_table(TABLES[0]), "spo2", 849) == [(1, True), (2, True)]
    assert evaluate(parse_table(TABLES[0]), "cssrs_plan", 1) == [(8, False)]
    assert evaluate(parse_table(TABLES[1]), "x", I64_MIN) == [(4, False)]
    print(f"tables: {len(tables)}  cases: {cases}  rejects: {len(REJECTS)}")
