"""scipy reference values for core/src/numerics.rs (ADR-0004).

Writes oracle/vectors/numerics_vectors.txt. Run: py -I oracle/numerics_ref.py
"""
import os

import numpy as np
from scipy import special, stats

out = ["# generated by oracle/numerics_ref.py - scipy " + __import__("scipy").__version__]
g = lambda v: repr(float(v))

for x in [1e-3, 0.1, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 5.0, 7.5, 10.0, 20.0, 50.0, 100.0, 1e3, 1e5] + list(
    np.exp(np.random.default_rng(1).uniform(np.log(1e-3), np.log(1e4), 60))
):
    out.append(f"lgamma\t{g(x)}\t{g(special.gammaln(x))}")

for a in [0.5, 1.0, 2.0, 3.5, 7.0, 12.5, 50.0]:
    for b in [0.5, 1.0, 2.0, 3.5, 7.0, 12.5, 50.0]:
        for x in [1e-10, 1e-4, 0.01, 0.1, 0.3, 0.5, 0.7, 0.9, 0.99, 0.9999]:
            out.append(f"betainc\t{g(a)}\t{g(b)}\t{g(x)}\t{g(1.0 - x)}\t{g(special.betainc(a, b, x))}")

# t-distribution tails: x and y computed the way t_to_z computes them.
for nu in [1.0, 2.0, 2.5, 4.0, 7.0, 15.0, 30.0, 100.0]:
    for t in [0.05, 0.5, 1.0, 2.0, 3.0, 5.0, 8.0, 12.0, 20.0, 40.0, 100.0, 1e4]:
        x, y = nu / (nu + t * t), t * t / (nu + t * t)
        out.append(f"betainc\t{g(nu / 2)}\t{g(0.5)}\t{g(x)}\t{g(y)}\t{g(special.betainc(nu / 2, 0.5, x))}")

ps = list(np.logspace(-300, np.log10(0.49), 80)) + [0.5, 0.51, 0.6, 0.75, 0.9, 0.975, 0.999, 1 - 1e-9, 1 - 1e-15]
for p in ps:
    out.append(f"ndtri\t{g(p)}\t{g(special.ndtri(p))}")

for nu in [1.0, 2.0, 2.5, 4.0, 7.0, 15.0, 30.0, 100.0, 1000.0]:
    for t in [0.1, 0.5, 1.0, 2.0, 3.0, 5.0, 8.0, 12.0, 20.0, 40.0, 100.0]:
        for s in (1, -1):
            tt = s * t
            z = stats.norm.isf(stats.t.sf(tt, nu)) if tt > 0 else stats.norm.ppf(stats.t.cdf(tt, nu))
            if np.isfinite(z):
                out.append(f"t2z\t{g(tt)}\t{g(nu)}\t{g(z)}")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors", "numerics_vectors.txt")
with open(path, "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print(f"vectors: {len(out) - 1}")
